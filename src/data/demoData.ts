export async function seedDemoDataInFirestore(adminUid: string): Promise<number> {
  try {
    const batch = writeBatch(db);
    let count = 0;

    // Seed default platform settings if not present
    batch.set(
      doc(db, 'admin_settings', 'platform'),
      {
        ...DEFAULT_ADMIN_SETTINGS,
        updatedBy: adminUid,
        updatedAt: serverTimestamp(),
      },
      { merge: true }
    );
    count++;

    for (const user of DEMO_USERS_PUBLIC) {
      batch.set(doc(db, 'users_public', user.uid), {
        ...user,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
      count++;
    }

    for (const task of DEMO_TASKS) {
      const { id, ...rest } = task;
      batch.set(doc(db, 'tasks', id), {
        ...rest,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
      count++;
    }

    for (const txn of DEMO_TRANSACTIONS) {
      const { id, ...rest } = txn;
      batch.set(doc(db, 'transactions', id), {
        ...rest,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
      count++;
    }

    for (const rev of DEMO_REVIEWS) {
      const { id, ...rest } = rev;
      batch.set(doc(db, 'reviews', id), {
        ...rest,
        createdAt: serverTimestamp(),
      });
      count++;
    }

    await batch.commit();
    return count;
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, 'demo_seed_batch');
  }
}

export async function clearDemoDataInFirestore(): Promise<number> {
  const collectionsToClean = [
    'tasks',
    'users_public',
    'applications',
    'transactions',
    'notifications',
    'conversations',
    'reviews',
    'disputes',
  ];

  let deleted = 0;
  try {
    for (const colName of collectionsToClean) {
      const q = query(collection(db, colName), where('isDemo', '==', true));
      const snap = await getDocs(q);
      if (snap.empty) continue;

      const batch = writeBatch(db);
      snap.docs.forEach((docSnap) => {
        batch.delete(docSnap.ref);
        deleted++;
      });
      await batch.commit();
    }
    return deleted;
  } catch (error) {
    handleFirestoreError(error, OperationType.DELETE, 'demo_clear_batch');
  }
}
